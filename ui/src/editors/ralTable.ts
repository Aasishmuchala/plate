export const RAL_BY_CODE: ReadonlyMap<string, RalColour> = new Map(RAL_CLASSIC.map((c) => [c.code, c]));

/**
 * Colours that match `query`, in table order. A leading `RAL` is ignored; the rest is split on spaces and every part
 * must fit: a number is a code prefix (`70` -> every 70xx, `7016` -> that one), a word is a part of the name
 * (`anthracite`, `light grey`). An empty query is the whole table.
 */
export function searchRal(query: string): readonly RalColour[] {
  const q = query.toLowerCase().replace(/^\s*ral(?=\s|\d|$)\s*/, "").trim();
  if (q === "") return RAL_CLASSIC;
  const parts = q.split(/\s+/);
  return RAL_CLASSIC.filter((c) => {
    const name = c.name.toLowerCase();
    return parts.every((p) => (/^\d+$/.test(p) ? c.code.startsWith(p) : name.includes(p)));
  });
}
