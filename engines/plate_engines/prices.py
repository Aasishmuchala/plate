"""Nightly price refresh from vendor catalogue fixtures, with the overlay file and the 5% requote rule.

New for the PLATE monorepo (router plan T27; BUILD_PLAN section 4 "Routing": prices refreshed nightly from vendor
catalogues; section 9: re-quote on price moves over 5%, never a silent fallback). Nothing here touches the
network: `refresh` reads catalogue JSON files from a directory (recorded fixtures in tests, files fetched by a
live job later) and writes the overlay.

Catalogue file format (one JSON file per vendor; the file name is free):

    {
      "vendor": "atlas",              # the Route.provider these prices belong to
      "as_of": "2026-10-18",          # ISO date of the catalogue
      "currency": "USD",              # optional; only USD is accepted
      "models": [
        {"id": "kwaivgi/kling-video-o3-4k/image-to-video",   # the route's model_slug, else the manifest model_id
         "unit": "per_second",        # flat | per_image | per_megapixel | per_second (must equal price.model)
         "usd": 0.357,                # the default-tier figure, what the router ranks on
         "tiers": {"atlas_discounted": 0.0536},   # optional; merged into price.by
         "available": true}           # optional, default true; false = the vendor lists it as gone
      ]
    }

A manifest is matched to the entry of its primary route (the first active route that is not a same-model
fallback): vendor = route.provider, id = route.model_slug or manifest.model_id. Fallback providers feed the
retirement check only. An entry whose unit differs from price.model is skipped (an `unit_mismatch` alert), never
guessed. A catalogue older than the overlay's own `as_of` for that engine is ignored, so a stale file cannot
undo a newer price.

The overlay (default `manifests/_prices.yaml`, `PLATE_PRICES_OVERLAY` or `overlay_path=` to move it) holds, per
engine, usd, by, status "confirmed" (a catalogue is what confirms a price, models.PriceSpec), source and as_of.
`load_manifests()` skips every `_*.yaml`; `apply_overlay` / `load_priced_manifests` lay the overlay over the
manifests. The file is rewritten only when its content changes, atomically (temp file then os.replace with a
retry, because Windows refuses a replace while a reader holds the file).

A PriceChange carries the signed percent move. `requote` is true when the move is over 5% in either direction
(a price that fell invalidates the approved quote too). `requote_runs` names the quoted runs to re-quote.
"""

from __future__ import annotations

import json
import math
import os
import time
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any

import yaml

from .health import AlertLog, as_alert_log
from .loader import DEFAULT_MANIFEST_DIR, load_manifests
from .models import EngineManifest, Route

REQUOTE_PCT = 5.0
OVERLAY_NAME = "_prices.yaml"
OVERLAY_ENV = "PLATE_PRICES_OVERLAY"
UNITS = ("flat", "per_image", "per_megapixel", "per_second")
_OVERLAY_HEADER = (
    "# Generated by plate_engines.prices.refresh from vendor catalogues. Do not edit by hand.\n"
    "# Laid over the manifests by prices.apply_overlay; load_manifests() skips files that start with '_'.\n"
)


class CatalogueError(ValueError):
    """A catalogue file is unreadable or does not match the documented format."""


class OverlayError(ValueError):
    """The overlay file is unreadable or malformed."""


def default_overlay_path() -> Path:
    env = os.environ.get(OVERLAY_ENV)
    return Path(env) if env else DEFAULT_MANIFEST_DIR / OVERLAY_NAME


# ---------------------------------------------------------------------------- catalogues


@dataclass(frozen=True)
class CatalogueEntry:
    vendor: str
    id: str
    unit: str
    usd: float
    tiers: Mapping[str, float] = field(default_factory=dict)
    available: bool = True
    as_of: str = ""


class Catalogue:
    """Vendor catalogues in memory: {vendor: {model id: CatalogueEntry}}."""

    def __init__(self, entries: Iterable[CatalogueEntry] = (), vendors: Iterable[str] = ()) -> None:
        self._by_vendor: dict[str, dict[str, CatalogueEntry]] = {v: {} for v in vendors}
        for e in entries:
            self._by_vendor.setdefault(e.vendor, {})[e.id] = e

    @property
    def vendors(self) -> set[str]:
        return set(self._by_vendor)

    def has_vendor(self, vendor: str) -> bool:
        return vendor in self._by_vendor

    def entry(self, vendor: str, model_id: str) -> CatalogueEntry | None:
        return self._by_vendor.get(vendor, {}).get(model_id)

    def model_ids(self, vendor: str, *, available_only: bool = True) -> set[str]:
        return {i for i, e in self._by_vendor.get(vendor, {}).items() if e.available or not available_only}


def as_catalogue(catalogue: Catalogue | Mapping[str, Iterable[str]]) -> Catalogue:
    """A Catalogue, or a plain {vendor: [model ids]} mapping (what the retirement check needs)."""
    if isinstance(catalogue, Catalogue):
        return catalogue
    entries = [
        CatalogueEntry(vendor=vendor, id=model, unit="flat", usd=0.0)
        for vendor, models in catalogue.items()
        for model in models
    ]
    return Catalogue(entries, vendors=catalogue.keys())


def _need(cond: bool, where: str, msg: str) -> None:
    if not cond:
        raise CatalogueError(f"{where}: {msg}")


def _number(value: Any) -> bool:
    return (
        isinstance(value, int | float) and not isinstance(value, bool) and math.isfinite(value) and value >= 0
    )


def parse_catalogue(raw: Any, where: str = "catalogue") -> list[CatalogueEntry]:
    _need(isinstance(raw, dict), where, "top level must be an object")
    vendor = raw.get("vendor")
    _need(isinstance(vendor, str) and bool(vendor), where, "vendor must be a non-empty string")
    as_of = raw.get("as_of")
    try:
        date.fromisoformat(as_of if isinstance(as_of, str) else "")
    except ValueError:
        raise CatalogueError(f"{where}: as_of must be an ISO date like 2026-10-18") from None
    _need(raw.get("currency", "USD") == "USD", where, "only USD catalogues are accepted")
    models = raw.get("models")
    _need(isinstance(models, list), where, "models must be a list")
    out: dict[str, CatalogueEntry] = {}
    for i, m in enumerate(models):
        at = f"{where} models[{i}]"
        _need(isinstance(m, dict), at, "must be an object")
        mid = m.get("id")
        _need(isinstance(mid, str) and bool(mid), at, "id must be a non-empty string")
        _need(m.get("unit") in UNITS, at, f"unit must be one of {UNITS}")
        _need(_number(m.get("usd")), at, "usd must be a number >= 0")
        tiers = m.get("tiers", {})
        _need(
            isinstance(tiers, dict) and all(isinstance(k, str) and k for k in tiers),
            at,
            "tiers must be {name: usd}",
        )
        _need(all(_number(v) for v in tiers.values()), at, "tier prices must be numbers >= 0")
        avail = m.get("available", True)
        _need(isinstance(avail, bool), at, "available must be true or false")
        _need(mid not in out, at, f"duplicate model id {mid!r}")
        out[mid] = CatalogueEntry(
            vendor=vendor,
            id=mid,
            unit=m["unit"],
            usd=float(m["usd"]),
            tiers={k: float(v) for k, v in tiers.items()},
            available=avail,
            as_of=as_of,
        )
    return list(out.values())


def load_catalogues(directory: str | Path) -> Catalogue:
    """Read every *.json in the directory (sorted by name). Same vendor in two files: the later as_of wins."""
    entries: dict[tuple[str, str], CatalogueEntry] = {}
    vendors: set[str] = set()
    for path in sorted(Path(directory).glob("*.json")):
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError) as exc:
            raise CatalogueError(f"{path.name}: unreadable JSON: {exc}") from exc
        for e in parse_catalogue(raw, path.name):
            vendors.add(e.vendor)
            old = entries.get((e.vendor, e.id))
            if old is None or e.as_of >= old.as_of:
                entries[(e.vendor, e.id)] = e
    return Catalogue(entries.values(), vendors=vendors)


# ---------------------------------------------------------------------------- overlay


def read_overlay(path: str | Path) -> dict[str, dict[str, Any]]:
    """{engine_id: {usd, by, status, source, as_of}}; {} when the file does not exist."""
    p = Path(path)
    if not p.exists():
        return {}
    try:
        raw = yaml.safe_load(p.read_text(encoding="utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError) as exc:
        raise OverlayError(f"{p.name}: unreadable YAML: {exc}") from exc
    if raw is None:
        return {}
    engines = raw.get("engines") if isinstance(raw, dict) else None
    if not isinstance(engines, dict):
        raise OverlayError(f"{p.name}: top level must be a mapping with an 'engines' mapping")
    out: dict[str, dict[str, Any]] = {}
    for engine_id, e in engines.items():
        if not isinstance(e, dict) or not _number(e.get("usd")):
            raise OverlayError(f"{p.name}: engines.{engine_id} needs a numeric usd")
        status = e.get("status", "confirmed")
        if status not in ("unconfirmed", "confirmed"):
            raise OverlayError(f"{p.name}: engines.{engine_id}.status must be unconfirmed or confirmed")
        by = e.get("by") or {}
        if not isinstance(by, dict) or not all(_number(v) for v in by.values()):
            raise OverlayError(f"{p.name}: engines.{engine_id}.by must map tier names to numbers")
        as_of = e.get("as_of")
        out[str(engine_id)] = {
            "usd": float(e["usd"]),
            "by": {str(k): float(v) for k, v in by.items()},
            "status": status,
            "source": str(e.get("source", "")),
            "as_of": as_of.isoformat() if isinstance(as_of, date) else (str(as_of) if as_of else ""),
        }
    return out


def _overlay_text(overlay: Mapping[str, Mapping[str, Any]]) -> str:
    doc = {"version": 1, "engines": {k: dict(v) for k, v in sorted(overlay.items())}}
    return _OVERLAY_HEADER + yaml.safe_dump(doc, sort_keys=True, default_flow_style=False)


def _replace_with_retry(src: Path, dst: Path, attempts: int = 8) -> None:
    for i in range(attempts):
        try:
            os.replace(src, dst)
            return
        except PermissionError:
            if i == attempts - 1:
                raise
            time.sleep(0.05 * (i + 1))


def write_overlay(path: str | Path, overlay: Mapping[str, Mapping[str, Any]]) -> bool:
    """Write the overlay atomically; returns False (and touches nothing) when the content is unchanged."""
    p = Path(path)
    text = _overlay_text(overlay)
    if p.exists():
        with open(p, encoding="utf-8", newline="") as fh:
            if fh.read() == text:
                return False
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(f"{p.name}.{os.getpid()}.tmp")
    try:
        with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        _replace_with_retry(tmp, p)
    finally:
        if tmp.exists():
            tmp.unlink()
    return True


def apply_overlay(
    manifests: Mapping[str, EngineManifest], overlay: Mapping[str, Mapping[str, Any]]
) -> dict[str, EngineManifest]:
    """The manifests with overlay prices laid over price.usd / by / status / source / as_of (copies; inputs unchanged)."""
    out = dict(manifests)
    for engine_id, o in overlay.items():
        m = out.get(engine_id)
        if m is None:
            continue
        as_of = o.get("as_of")
        price = m.price.model_copy(
            update={
                "usd": float(o["usd"]),
                "by": {**m.price.by, **dict(o.get("by") or {})},
                "status": o.get("status", m.price.status),
                "source": o.get("source") or m.price.source,
                "as_of": date.fromisoformat(as_of) if as_of else m.price.as_of,
            }
        )
        out[engine_id] = m.model_copy(update={"price": price})
    return out


def load_priced_manifests(
    manifest_dir: str | Path | None = None, overlay_path: str | Path | None = None
) -> dict[str, EngineManifest]:
    """load_manifests() with the overlay laid over it (no overlay file = the manifests as they are)."""
    manifests = load_manifests(Path(manifest_dir)) if manifest_dir else load_manifests()
    if overlay_path is None:
        overlay_path = Path(manifest_dir) / OVERLAY_NAME if manifest_dir else default_overlay_path()
    return apply_overlay(manifests, read_overlay(overlay_path))


# ---------------------------------------------------------------------------- refresh


@dataclass(frozen=True)
class PriceChange:
    """One price that moved. tier None is the default-tier usd; otherwise the key in price.by."""

    engine_id: str
    old: float
    new: float
    pct: float  # signed percent move, (new - old) / old * 100; inf when old was 0 and new is not
    tier: str | None = None
    vendor: str = ""
    as_of: str = ""

    @property
    def requote(self) -> bool:
        return (
            round(abs(self.pct), 6) > REQUOTE_PCT
        )  # rounded so 105 vs 100 is exactly 5.0, not 5.000000000000004

    def to_dict(self) -> dict[str, Any]:
        return {
            "engine_id": self.engine_id,
            "tier": self.tier,
            "old": self.old,
            "new": self.new,
            "pct": self.pct if math.isfinite(self.pct) else None,
            "requote": self.requote,
            "vendor": self.vendor,
            "as_of": self.as_of,
        }


class PriceChanges(list):
    """The list of PriceChange refresh() found, plus what it skipped and why (`skipped`, one line each)."""

    def __init__(self, items: Iterable[PriceChange] = ()) -> None:
        super().__init__(items)
        self.skipped: list[str] = []

    @property
    def requotes(self) -> list[PriceChange]:
        return [c for c in self if c.requote]


def pct_change(old: float, new: float) -> float:
    if old == 0:
        return 0.0 if new == 0 else math.inf
    return (new - old) / old * 100.0


def primary_route(manifest: EngineManifest) -> Route | None:
    return next(
        (r for r in manifest.routes if r.status == "active" and r.same_model_fallback_of is None), None
    )


def _differs(a: float, b: float) -> bool:
    return not math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-12)


def refresh(
    catalogue_fixtures_dir: str | Path,
    *,
    manifests: Mapping[str, EngineManifest] | None = None,
    overlay_path: str | Path | None = None,
    alerts: AlertLog | str | Path | None = None,
    write: bool = True,
) -> PriceChanges:
    """Compare the vendor catalogues with the current prices; write the overlay; return what moved.

    `old` is the price in force (overlay over manifest), `new` the catalogue's. With `alerts`, a price_change
    alert is appended per move (severity warn when it needs a requote) and an unit_mismatch alert per skip.
    `write=False` computes without touching the overlay.
    """
    log = as_alert_log(alerts)
    base = dict(manifests) if manifests is not None else load_manifests()
    path = Path(overlay_path) if overlay_path else default_overlay_path()
    catalogue = load_catalogues(catalogue_fixtures_dir)
    overlay = read_overlay(path)
    in_force = apply_overlay(base, overlay)
    new_overlay = {k: dict(v) for k, v in overlay.items()}
    changes = PriceChanges()

    for engine_id in sorted(base):
        manifest = in_force[engine_id]
        route = primary_route(manifest)
        model = (route.model_slug or manifest.model_id) if route else None
        if route is None or model is None:
            continue
        entry = catalogue.entry(route.provider, model)
        if entry is None:
            continue
        price = manifest.price
        if not entry.available:
            changes.skipped.append(
                f"{engine_id}: {route.provider} lists {model} as unavailable; price left as is"
            )
            continue
        if entry.unit != price.model:
            note = f"{engine_id}: catalogue unit {entry.unit!r} differs from price.model {price.model!r}; skipped"
            changes.skipped.append(note)
            if log is not None:
                log.write(
                    "unit_mismatch", note, severity="warn", engine_id=engine_id, route_id=route.route_id
                )
            continue
        have = overlay.get(engine_id)
        if have and have.get("as_of") and entry.as_of < have["as_of"]:
            changes.skipped.append(
                f"{engine_id}: catalogue as_of {entry.as_of} is older than the overlay's {have['as_of']}; skipped"
            )
            continue

        found: list[PriceChange] = []
        if _differs(price.usd, entry.usd):
            found.append(
                PriceChange(
                    engine_id,
                    price.usd,
                    entry.usd,
                    pct_change(price.usd, entry.usd),
                    None,
                    route.provider,
                    entry.as_of,
                )
            )
        by = dict(price.by)
        for tier, usd in entry.tiers.items():
            if tier in by and _differs(by[tier], usd):
                found.append(
                    PriceChange(
                        engine_id, by[tier], usd, pct_change(by[tier], usd), tier, route.provider, entry.as_of
                    )
                )
            by[tier] = usd
        new_overlay[engine_id] = {
            "usd": entry.usd,
            "by": by,
            "status": "confirmed",
            "source": f"catalogue:{route.provider}",
            "as_of": entry.as_of,
        }
        changes.extend(found)
        if log is not None:
            for c in found:
                where = f"{c.engine_id}" + (f" tier {c.tier}" if c.tier else "")
                move = "an unknown percent" if not math.isfinite(c.pct) else f"{c.pct:+.1f}%"
                log.write(
                    "price_change",
                    f"{where}: {c.old:g} -> {c.new:g} USD ({move})"
                    + ("; quoted runs need a requote" if c.requote else ""),
                    severity="warn" if c.requote else "info",
                    engine_id=c.engine_id,
                    route_id=route.route_id,
                    data=c.to_dict(),
                )

    if write and new_overlay != overlay:
        write_overlay(path, new_overlay)
    return changes


def requote_runs(
    changes: Iterable[PriceChange],
    quoted_runs: Iterable[Mapping[str, Any]],
    alerts: AlertLog | str | Path | None = None,
) -> list[str]:
    """run_ids of quoted runs whose engine's price moved over 5%: those quotes must be redone before approval.

    quoted_runs are mappings with run_id and engine_id and, when quoted on a named tier, tier. A change matches a
    run when the engine and the tier agree (no tier = the default usd).
    """
    log = as_alert_log(alerts)
    moved = [c for c in changes if c.requote]
    flagged: list[str] = []
    for run in quoted_runs:
        run_id, engine_id, tier = run.get("run_id"), run.get("engine_id"), run.get("tier")
        for c in moved:
            if c.engine_id != engine_id or c.tier != tier:
                continue
            if run_id not in flagged:
                flagged.append(run_id)
                if log is not None:
                    log.write(
                        "requote",
                        f"run {run_id}: {engine_id} price moved {c.pct:+.1f}%; quote again before approval",
                        severity="warn",
                        engine_id=engine_id,
                        data={"run_id": run_id, "pct": c.pct if math.isfinite(c.pct) else None},
                    )
            break
    return flagged
